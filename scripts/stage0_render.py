"""Render the Stage 0 gate's JSON into the LaTeX tables docs/stage0_gate.tex includes.

Every number in the document comes from here, never typed by hand: the tables
are `tabular` fragments written to --out, each headed by a comment naming the
result file, the commit and the job that produced it, and provenance.tex
defines the macros the document cites them with.

  uv run python scripts/stage0_render.py docs/stage0/stage0_<jobid> --out docs/stage0/tables
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

THIRDS = ("low", "middle", "high")
THIRD_LABEL = {"low": "low third", "middle": "middle third", "high": "high third"}


def tex(s) -> str:
    """Escape a path or name for LaTeX text."""
    return str(s).replace("\\", "/").replace("_", "\\_").replace("%", "\\%").replace("#", "\\#")


def pct(x: float) -> str:
    return f"{100 * x:.1f}\\%"


def num(x: float, d: int = 1) -> str:
    return f"{x:.{d}f}".replace("-", "$-$")


def outcomes(o: dict) -> str:
    parts = []
    for k in ("shower", "timeout", "seeds_dissolved", "policy_exception", "probe_failed", "see errors"):
        if o.get(k):
            parts.append(f"{o[k]} {k.replace('_', ' ')}")
    return ", ".join(parts) if parts else "none"


def physical(fam: str, q: dict) -> str:
    if fam == "track":
        return f"level {q['level']:.4f}"
    if fam == "linear":
        return f"{q['rate_degC_per_min']:.3f} $^\\circ$C/min"
    if fam == "power":
        return f"$\\tau$ {q['tau_min']:.0f} min, $n$ {q['exponent']:.2f}"
    if fam == "hybrid":
        return f"$\\tau$ {q['tau_min']:.0f} min, $n$ {q['exponent']:.2f}, cap {q['cap']:.4f}"
    if fam == "pwl":
        return "10 knobs"
    return ""


class Writer:
    def __init__(self, out: Path, header: str):
        self.out = out
        self.header = header
        out.mkdir(parents=True, exist_ok=True)

    def write(self, name: str, lines: list[str]) -> None:
        (self.out / name).write_text(self.header + "\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("results_dir", help="directory holding stage0_results.json (and the job log)")
    ap.add_argument("--out", required=True, help="directory for the .tex fragments")
    ap.add_argument("--macro-prefix", default="SZ", help="prefix of the provenance macros (one per run in a document)")
    args = ap.parse_args()
    P = args.macro_prefix
    rdir = Path(args.results_dir)
    R = json.loads((rdir / "stage0_results.json").read_text())
    prov, cfg = R["provenance"], R["config"]
    job = prov["slurm"].get("job_id", "none")
    commit = prov["commit"][:7]
    logs = sorted(rdir.glob("*.out"))
    log_path = str(logs[0]) if logs else str(rdir / "stage0_summary.txt")
    header = (f"% GENERATED by scripts/stage0_render.py from {rdir / 'stage0_results.json'}\n"
              f"% code commit {prov['commit']}, Slurm job {job}, host {prov['hostname']}, {prov['started_utc']}\n"
              "% Do not edit; re-run the renderer.\n")
    W = Writer(Path(args.out), header)
    anchors = [str(a) for a in cfg["anchors"]]
    families = list(cfg["families"])

    # ---- provenance macros ----------------------------------------------------------------
    b = cfg["budget"]
    W.write("provenance.tex", [
        f"\\newcommand{{\\{P}commit}}{{{commit}}}",
        f"\\newcommand{{\\{P}commitfull}}{{{prov['commit']}}}",
        f"\\newcommand{{\\{P}job}}{{{job}}}",
        f"\\newcommand{{\\{P}host}}{{{tex(prov['hostname'])}}}",
        f"\\newcommand{{\\{P}date}}{{{prov['started_utc'][:10]}}}",
        f"\\urldef{{\\{P}results}}\\path{{{rdir / 'stage0_results.json'}}}",
        f"\\urldef{{\\{P}rows}}\\path{{{rdir / 'stage0_rows.json'}}}",
        f"\\urldef{{\\{P}log}}\\path{{{log_path}}}",
        f"\\newcommand{{\\{P}seconds}}{{{R['seconds']:.0f}}}",
        f"\\newcommand{{\\{P}workers}}{{{prov['slurm'].get('cpus_per_task', '?')}}}",
        f"\\newcommand{{\\{P}nrandom}}{{{b['n_random']}}}",
        f"\\newcommand{{\\{P}topk}}{{{b['topk']}}}",
        f"\\newcommand{{\\{P}nclimb}}{{{b['n_climb']}}}",
        f"\\newcommand{{\\{P}nevals}}{{{b['n_random'] + b['topk'] * b['n_climb']}}}",
        f"\\newcommand{{\\{P}searchseeds}}{{{cfg['search_seeds'][0]} to {cfg['search_seeds'][1]}}}",
        f"\\newcommand{{\\{P}nsearch}}{{{cfg['search_seeds'][2]}}}",
        f"\\newcommand{{\\{P}freshseeds}}{{{cfg['fresh_seeds'][0]} to {cfg['fresh_seeds'][1]}}}",
        f"\\newcommand{{\\{P}nfresh}}{{{cfg['fresh_seeds'][2]}}}",
        f"\\newcommand{{\\{P}neval}}{{{cfg['inputs']['n_eval_tasks']}}}",
        f"\\newcommand{{\\{P}evalsha}}{{{cfg['inputs']['crystallizer_eval.jsonl'][:12]}}}",
        f"\\newcommand{{\\{P}searchseed}}{{{cfg['search_seed']}}}",
        f"\\newcommand{{\\{P}fastfactor}}{{{cfg['fast_factor']}}}",
        f"\\newcommand{{\\{P}timeweight}}{{{cfg['env']['time_weight']}}}",
        f"\\newcommand{{\\{P}margin}}{{{cfg['controller_margin']}}}",
    ])

    # ---- blind side per family -------------------------------------------------------------
    lines = ["\\begin{tabular}{@{}llrrrrl@{}}", "\\toprule",
             "Family & Tuned to & Reward & Success & Fast & Norm.\\ time & Failures \\\\", "\\midrule"]
    blind = R["search"]["blind"]
    for fam in sorted(families, key=lambda f: -blind[f]["eval"]["reward"]):
        e = blind[fam]["eval"]
        lines.append(f"{fam} & {physical(fam, blind[fam]['physical'])} & {num(e['reward'])} & {pct(e['success'])} & "
                     f"{pct(e['fast'])} & {num(e['norm_time'], 3)} & {outcomes(e['outcomes'])} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    W.write("blind.tex", lines)

    # ---- informed side per family per anchor ------------------------------------------------
    inf = R["search"]["informed"]
    cols = "r" * len(anchors)
    lines = [f"\\begin{{tabular}}{{@{{}}l{cols}{cols}@{{}}}}", "\\toprule",
             f" & \\multicolumn{{{len(anchors)}}}{{c}}{{Fast success}} & \\multicolumn{{{len(anchors)}}}{{c}}{{Mean reward}} \\\\",
             f"\\cmidrule(lr){{2-{1 + len(anchors)}}}\\cmidrule(lr){{{2 + len(anchors)}-{1 + 2 * len(anchors)}}}",
             "Family & " + " & ".join(f"${a}$" for a in anchors) + " & " + " & ".join(f"${a}$" for a in anchors) + " \\\\",
             "\\midrule"]
    for fam in sorted(families, key=lambda f: -sum(inf[a][f]["eval"]["fast"] for a in anchors)):
        fast = " & ".join(pct(inf[a][fam]["eval"]["fast"]) for a in anchors)
        rew = " & ".join(num(inf[a][fam]["eval"]["reward"]) for a in anchors)
        lines.append(f"{fam} & {fast} & {rew} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    W.write("informed.tex", lines)

    # ---- the two blind references and the searched blind controller, by third -----------------
    caut = R["cautious"]
    bb = blind[R["verdicts"]["best_blind_family"]]
    lines = ["\\begin{tabular}{@{}llrrrrl@{}}", "\\toprule",
             "Controller & Batches & Reward & Success & Fast & Norm.\\ time & Failures \\\\", "\\midrule"]
    for name, src in (("cautious (rides at 0.08)", caut), (f"searched blind ({R['verdicts']['best_blind_family']}, {physical(R['verdicts']['best_blind_family'], bb['physical'])})", bb)):
        for th in THIRDS:
            e = src["eval_by_third"][th]
            lines.append(f"{name if th == 'low' else ''} & {THIRD_LABEL[th]} & {num(e['reward'])} & {pct(e['success'])} & "
                         f"{pct(e['fast'])} & {num(e['norm_time'], 3)} & {outcomes(e['outcomes'])} \\\\")
        e = src["eval"]
        lines.append(f" & all & {num(e['reward'])} & {pct(e['success'])} & {pct(e['fast'])} & {num(e['norm_time'], 3)} & {outcomes(e['outcomes'])} \\\\")
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines.append("\\end{tabular}")
    W.write("blind_references.tex", lines)

    # ---- verdicts ---------------------------------------------------------------------------
    v = R["verdicts"]
    bi = v["best_informed"]
    lines = ["\\begin{tabular}{@{}lll@{}}", "\\toprule", "Gate & Measured & Verdict \\\\", "\\midrule",
             "G1: informed fast success $\\ge 90\\%$ at every anchor & " +
             ", ".join(f"${a}$: {pct(bi[a]['fast'])} ({bi[a]['family']})" for a in anchors) +
             f" & {'pass' if v['G1'] else 'fail'} \\\\",
             f"G2: blind at least 40 points below informed & blind {pct(v['blind_fast_range'])} over the range "
             f"({v['best_blind_family']}, {physical(v['best_blind_family'], v['best_blind_physical'])}), "
             f"informed mean {pct(v['informed_mean_fast'])}, gap {v['gap_pp']:+.0f} pp & {'pass' if v['G2'] else 'fail'} \\\\",
             "G3: probe run + controller fast $\\ge 95\\%$ at every anchor, no probe failure & " +
             ", ".join(f"${a}$: {pct(v['g3_fast_at_anchors'][a])}" for a in anchors) +
             f" & {'pass' if v['G3'] else 'fail'} \\\\",
             "\\bottomrule", "\\end{tabular}"]
    W.write("verdicts.tex", lines)

    # ---- G3 variants ------------------------------------------------------------------------
    g3 = R["g3"]
    lines = ["\\begin{tabular}{@{}lrrrrrrr@{}}", "\\toprule",
             "Probe variant & Fast & Norm.\\ time & Reward & Probe failures & Error median & Error p90 & Error max \\\\", "\\midrule"]
    for variant in cfg["probe_variants"]:
        s = g3[variant]["range"]
        pe = s["probe_error"] or {"median": float("nan"), "p90": float("nan"), "max": float("nan")}
        lines.append(f"{variant} & {pct(s['fast'])} & {num(s['norm_time'], 3)} & {num(s['reward'])} & {s['probe_failures']} & "
                     f"{num(pe['median'], 4)} & {num(pe['p90'], 4)} & {num(pe['max'], 4)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    W.write("g3_variants.tex", lines)

    gate = g3[cfg["gate_variant"]]
    lines = ["\\begin{tabular}{@{}lrrrrrr@{}}", "\\toprule",
             "Batches & Fast & Norm.\\ time & Min norm.\\ time & Reward & Probe failures & Error max \\\\", "\\midrule"]
    for a in anchors:
        s = gate["anchors"][a]
        lines.append(f"anchor ${a}$ & {pct(s['fast'])} & {num(s['norm_time'], 3)} & {num(s['min_norm_time'], 3)} & {num(s['reward'])} & {s['probe_failures']} & {num(s['probe_error']['max'], 4)} \\\\")
    for th in THIRDS:
        s = gate["range_by_third"][th]
        lines.append(f"range, {THIRD_LABEL[th]} & {pct(s['fast'])} & {num(s['norm_time'], 3)} & {num(s['min_norm_time'], 3)} & {num(s['reward'])} & {s['probe_failures']} & {num(s['probe_error']['max'], 4)} \\\\")
    s = gate["range"]
    lines.append(f"range, all & {pct(s['fast'])} & {num(s['norm_time'], 3)} & {num(s['min_norm_time'], 3)} & {num(s['reward'])} & {s['probe_failures']} & {num(s['probe_error']['max'], 4)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    W.write("g3_gate.tex", lines)

    # ---- references on the held-out evaluation tasks ----------------------------------------
    refs = R["references"]
    lines = ["\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule",
             "Reference & Batches & Steps & Reward & Success & Fast & Norm.\\ time \\\\", "\\midrule"]
    names = (("oracle", "oracle (rides at the limit)"), ("cautious", "cautious blind (rides at 0.08)"),
             ("blind_searched", "searched blind"), ("probe_controller", "probe run + controller"))
    for key, label in names:
        for th in THIRDS + ("all",):
            s = refs[key]["overall"] if th == "all" else refs[key]["by_third"][th]
            lines.append(f"{label if th == 'low' else ''} & {THIRD_LABEL.get(th, 'all')} & {num(s['steps'])} & {num(s['reward'])} & "
                         f"{pct(s['success'])} & {pct(s['fast'])} & {num(s['norm_time'], 3)} \\\\")
        lines.append("\\midrule")
    lines[-1] = "\\bottomrule"
    lines.append("\\end{tabular}")
    W.write("references.tex", lines)
    # ---- code listings, from the module itself so the document cannot drift from the code --
    import sys
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from stage0_solution import CONTROLLER_MARGIN, CONTROLLER_TEMPLATE, PROBE_VARIANTS, GATE_VARIANT, RANGE_BOTTOM
    W.write("listing_probe.tex", ["\\begin{verbatim}", PROBE_VARIANTS[GATE_VARIANT].strip("\n"), "\\end{verbatim}"])
    W.write("listing_controller.tex", ["\\begin{verbatim}",
                                       CONTROLLER_TEMPLATE.replace("{sigma_hat:.5f}", "<SIGMA_MAX_LOW>")
                                       .replace("{margin}", str(CONTROLLER_MARGIN)).replace("{range_bottom}", str(RANGE_BOTTOM))
                                       .replace("{{", "{").replace("}}", "}").strip("\n"),
                                       "\\end{verbatim}"])
    print(f"wrote {len(list(Path(args.out).glob('*.tex')))} fragments to {args.out} from {rdir} (commit {commit}, job {job})")


if __name__ == "__main__":
    main()
