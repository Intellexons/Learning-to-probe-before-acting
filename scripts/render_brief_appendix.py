"""Render the paper's appendix "The brief" from the code that builds the prompt.

Writes docs/assets/brief_appendix.tex: the prompt of a two-reply task exactly
as the chat template renders it for the first held-out task (the system
message with the definition of the one tool, then the brief), followed by one
exchange (a `probe_run` call and its tool response) in the same rendering.
Lines are wrapped for print; nothing is typed by hand.

  uv run python scripts/render_brief_appendix.py
"""
from __future__ import annotations

import argparse
import json
import sys
import textwrap
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from src.agent_loop import TOOL_PROBE, render_tool_call, tool_message, tools_for  # noqa: E402
from src.prompts import load_template, render_prompt  # noqa: E402

WIDTH = 92


def wrap(text: str) -> str:
    """Wrap long lines for print; a wrapped line continues with four spaces.
    Lines of the batch logs and of code are short and pass through."""
    out = []
    for line in text.splitlines():
        if len(line) <= WIDTH:
            out.append(line)
            continue
        lead = line[: len(line) - len(line.lstrip())]
        out.extend(textwrap.wrap(line, WIDTH, initial_indent="", subsequent_indent=lead + "    ",
                                 break_long_words=False, break_on_hyphens=False))
    return "\n".join(out)


def verbatim(text: str) -> str:
    assert "\\end{verbatim}" not in text
    return "\\begin{scriptsize}\n\\begin{verbatim}\n" + wrap(text.rstrip("\n")) + "\n\\end{verbatim}\n\\end{scriptsize}\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--task-file", default="scripts/seed_tasks/crystallizer_eval.jsonl")
    ap.add_argument("--tokenizer", default="models/hf_base/iter_000")
    ap.add_argument("--out", default="docs/assets/brief_appendix.tex")
    args = ap.parse_args()

    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(args.tokenizer)
    task = json.loads(Path(args.task_file).read_text().splitlines()[0])
    tools = tools_for(2)
    chat = [{"role": "user", "content": render_prompt(load_template(str(REPO / "configs" / "prompt_template.txt")), task, total_turns=2)}]
    prompt = tok.apply_chat_template(chat, tools=tools, tokenize=False, add_generation_prompt=True)
    reply = render_tool_call(TOOL_PROBE, "<the probe code>")
    after = tok.apply_chat_template(
        chat + [{"role": "assistant", "content": reply}, tool_message("SIGMA_MAX_LOW=0.18100 SIGMA_MAX_HIGH=0.18240")],
        tools=tools, tokenize=False, add_generation_prompt=True)
    assert after.startswith(prompt)

    body = (
        "% GENERATED by scripts/render_brief_appendix.py. Do not edit; re-run the script.\n"
        f"% task {task['task_id']} of {args.task_file}; chat template of {args.tokenizer}.\n"
        "The prompt of a two-reply task as the model receives it, rendered by the chat template for one\n"
        "held-out task: the system message, into which the template writes the definition of the one tool,\n"
        "then the brief. With one reply there is no tool: the system message is its first line alone, and\n"
        "the brief has no section on the probe run. Lines are wrapped for print.\n\n"
        + verbatim(prompt)
        + "\nA reply that calls the tool is a probe run: what the code printed comes back as the tool response,\n"
        "and the model replies again. A reply without a tool call is the final answer.\n\n"
        + verbatim(after[len(prompt):])
    )
    out = REPO / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(body)
    print(f"wrote {out} ({len(prompt)} characters of prompt)")


if __name__ == "__main__":
    main()
